"""Summarise runs.jsonl into the measured section of COSTS.md (between the COSTS markers).

Everything comes from logged calls; nothing is estimated except list-price USD, which uses the
[prices] table in config.toml. Mock lines are excluded (they live in build/mock/runs.jsonl anyway).
"""
from __future__ import annotations

import json
import re
from collections import defaultdict

from .common import CONFIG, MOCK, ROOT, RUNS, now, say

BEGIN, END = "<!-- COSTS:BEGIN (generated by `make costs`) -->", "<!-- COSTS:END -->"


def gpu_rate(gpu: str | None) -> float:
    rates = CONFIG["prices"]["gpu_usd_per_hour"]
    return next((v for k, v in rates.items() if gpu and k.lower() in gpu.lower()), 0.0)


def main() -> None:
    lines = [json.loads(l) for l in RUNS.read_text().splitlines() if l.strip()] if RUNS.exists() else []
    rows = [r for r in lines if bool(r.get("mock")) == MOCK]
    groups = defaultdict(list)
    for r in rows:
        groups[(r.get("stage"), r.get("provider"), r.get("model"))].append(r)

    out = ["| Stage | Provider | Model | Calls ok/err | Total latency (s) | Mean (s) | GPU min | "
           "Tokens in/out | Neurons (est.) | List-price USD |", "|" + "---|" * 10]
    tot = defaultdict(float)
    for (stage, provider, model), rs in sorted(groups.items(), key=lambda kv: [str(x) for x in kv[0]]):
        ok = [r for r in rs if r.get("status") == "ok"]
        lat = sum(r.get("latency_s") or 0 for r in ok)
        gpu_min = sum(r.get("gpu_s") or 0 for r in rs) / 60
        cost = [r.get("cost") or {} for r in ok]
        tin = sum(c.get("input_tokens", 0) for c in cost)
        tout = sum(c.get("output_tokens", 0) + c.get("audio_tokens", 0) for c in cost)
        neurons = sum(c.get("neurons_est", 0) for c in cost)
        usd = sum(c.get("usd_list", 0) for c in cost) + sum((r.get("gpu_s") or 0) / 3600 * gpu_rate(r.get("gpu")) for r in rs)
        for k, v in (("ok", len(ok)), ("err", len(rs) - len(ok)), ("lat", lat), ("gpu", gpu_min), ("neurons", neurons), ("usd", usd)):
            tot[k] += v
        out.append(f"| {stage} | {provider} | {model} | {len(ok)}/{len(rs) - len(ok)} | {lat:.1f} | "
                   f"{lat / len(ok) if ok else 0:.2f} | {gpu_min:.1f} | {tin}/{tout} | {neurons:.0f} | {usd:.4f} |")
    out.append(f"| **total** | | | {tot['ok']:.0f}/{tot['err']:.0f} | {tot['lat']:.1f} | | {tot['gpu']:.1f} | | "
               f"{tot['neurons']:.0f} | {tot['usd']:.4f} |")
    runs = sorted({r.get("run_id") for r in rows if r.get("run_id")})
    block = "\n".join([BEGIN, f"_Generated {now()} from {len(rows)} logged calls in {len(runs)} runs "
                       f"({RUNS.name}). Prices checked {CONFIG['prices']['checked_on']}._", "", *out, END])
    print(block)
    doc = ROOT / "COSTS.md"
    if MOCK or not doc.exists():
        return
    text = doc.read_text(encoding="utf-8")
    pattern = re.escape(BEGIN) + ".*?" + re.escape(END)
    new = re.sub(pattern, lambda _: block, text, flags=re.S) if BEGIN in text else text + "\n" + block + "\n"
    doc.write_text(new, encoding="utf-8")
    say("costs", "COSTS.md updated")


if __name__ == "__main__":
    main()
